    pair_id = int(row["pair_id"])
    gamma_n_used = float(row["gamma_n_used"])
    k_pen_base = float(row["k_pen_base"])
    k_pen_used = float(row["k_pen_used"])
    ensure_finite(gamma_n_used, "fem gamma_n_used")
    ensure_finite(k_pen_base, "fem k_pen_base")
    ensure_finite(k_pen_used, "fem k_pen_used")
    expected_key = (load_step, pair_id)
    manifest_row = fem_feedback_manifest_map.get(expected_key)
    feedback_row = fem_feedback_map.get(expected_key)
    fallback_applied = row["feedback_source"] != "EXTERNAL"
    if load_step > 0:
        later_step_fem_replay_use_rows += 1
