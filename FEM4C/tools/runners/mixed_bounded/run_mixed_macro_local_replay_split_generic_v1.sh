    key = (
        load_step,
        int(row["pair_id"]),
        int(row["slave_node_id"]),
        int(row["master_segment_id"]),
    )
    baseline_row = fem_baseline_map.get(key)
    if baseline_row is None:
        fail(f"missing FEM baseline row for {key!r}")
    fn_diff = abs(float(row["fn_n"]) - float(baseline_row["fn_n"]))
    penetration_diff = abs(float(row["penetration_m"]) - float(baseline_row["penetration_m"]))
    if load_step > 0:
        later_step_fem_replay_trace_rows += 1
    if fn_diff > 1.0e-9 or penetration_diff > 1.0e-12:
        fem_changed_rows += 1
        if load_step > 0:
            later_step_fem_changed_rows += 1

engine_histogram = mixed_feedback_summary.get("source_engine_histogram")
if not isinstance(engine_histogram, dict):
    fail("mixed feedback summary missing source_engine_histogram")
fem_load_steps = mixed_feedback_summary.get("fem_load_steps")
if not isinstance(fem_load_steps, list):
    fail("mixed feedback summary missing fem_load_steps")
mbd_source_rows = int(mixed_feedback_summary.get("mbd_source_rows", 0))
mbd_valid_source_rows = int(mixed_feedback_summary.get("mbd_valid_source_rows", 0))
mbd_invalid_source_rows = int(mixed_feedback_summary.get("mbd_invalid_source_rows", 0))
later_step_fem_feedback_rows = int(mixed_feedback_summary.get("later_step_fem_feedback_rows", 0))
later_step_fem_valid_source_rows = int(mixed_feedback_summary.get("later_step_fem_valid_source_rows", 0))
later_step_fem_invalid_source_rows = int(mixed_feedback_summary.get("later_step_fem_invalid_source_rows", 0))
feedback_available_flag = len(source_rows) > 0
skip_reason = "" if feedback_available_flag else "no_feedback_rows"
feedback_row_count = len(source_rows)
feedback_apply_count = mbd_external_rows + fem_external_rows
last_available_feedback_ref = None
