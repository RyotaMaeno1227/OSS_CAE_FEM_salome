python3 - "${FEM_DECK}" "${REDUCED_DIR}/fem_local_feedback_reduced.csv" "${FEM_REPLAY_DIR}/replay_from_mixed_feedback.dat" <<'PY'
from pathlib import Path
import shutil
import sys


deck_path = Path(sys.argv[1]).resolve()
feedback_csv = Path(sys.argv[2]).resolve()
replay_deck = Path(sys.argv[3]).resolve()
deck_dir = deck_path.parent
replay_dir = replay_deck.parent

deck_text = deck_path.read_text(encoding="utf-8")
for directive in ("FEM_LOCAL_FEEDBACK_MODE", "FEM_LOCAL_CONTACT_FILE"):
    for line in deck_text.splitlines():
        if line.strip().startswith(directive):
            raise SystemExit(f"FAIL: baseline FEM deck already contains {directive}: {deck_path}")

for raw_line in deck_text.splitlines():
    line = raw_line.strip()
    if not line or line.startswith("#"):
        continue
    fields = line.split()
    if fields[0] != "FEM_CONTACT_SURFACE_EDGE_SET" or len(fields) < 4:
        continue
    source_path = Path(fields[3])
    if source_path.is_absolute():
        continue
    resolved_source = (deck_dir / source_path).resolve()
    target_path = replay_dir / source_path.name
    if not resolved_source.is_file():
        raise SystemExit(f"FAIL: missing relative surface CSV referenced by deck: {resolved_source}")
    shutil.copyfile(resolved_source, target_path)

replay_text = (
    f"{deck_text.rstrip()}\n"
    "# autogenerated mixed split replay handoff for FEM\n"
    "FEM_LOCAL_FEEDBACK_MODE LAGGED_REDUCED\n"
