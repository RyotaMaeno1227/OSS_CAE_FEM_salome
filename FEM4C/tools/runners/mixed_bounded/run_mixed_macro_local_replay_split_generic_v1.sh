#!/usr/bin/env bash
set -euo pipefail

resolve_workspace_root() {
    local start_dir="${1:-$(pwd)}"
    local candidate="${start_dir}"
    while [[ "${candidate}" != "/" ]]; do
        if [[ -d "${candidate}/scripts" && -d "${candidate}/docs" && -d "${candidate}/examples" ]]; then
            printf '%s\n' "${candidate}"
            return 0
        fi
        candidate="$(dirname "${candidate}")"
    done
    local git_root=""
    git_root="$(git -C "${start_dir}" rev-parse --show-toplevel 2>/dev/null || true)"
    if [[ -n "${git_root}" && -d "${git_root}/FEM4C/scripts" && -d "${git_root}/FEM4C/docs" && -d "${git_root}/FEM4C/examples" ]]; then
        printf '%s\n' "${git_root}/FEM4C"
        return 0
    fi
    if [[ -n "${git_root}" && -d "${git_root}/scripts" && -d "${git_root}/docs" && -d "${git_root}/examples" ]]; then
        printf '%s\n' "${git_root}"
        return 0
    fi
    echo "FAIL: unable to resolve workspace root" >&2
    return 1
}

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(resolve_workspace_root "${SCRIPT_DIR}")"

if [[ $# -ne 4 ]]; then
    echo "Usage: bash tools/runners/mixed_bounded/run_mixed_macro_local_replay_split_generic_v1.sh <mixed_manifest.json|mixed_oneway_outdir> <mbd_deck> <fem_deck> <outdir>" >&2
    exit 2
fi

MIXED_INPUT="$1"
MBD_DECK="$2"
FEM_DECK="$3"
OUT_DIR="$4"

MIXED_ONEWAY_DIR="${OUT_DIR}/mixed_oneway"
REDUCED_DIR="${MIXED_ONEWAY_DIR}/reduced_feedback"
MBD_REPLAY_DIR="${OUT_DIR}/mbd_replay"
FEM_REPLAY_DIR="${OUT_DIR}/fem_replay"
HANDOFF_MANIFEST="${OUT_DIR}/split_replay_handoff_manifest.json"
SUMMARY_JSON="${OUT_DIR}/mixed_split_replay_summary.json"
SUMMARY_MD="${OUT_DIR}/mixed_split_replay_summary.md"

rm -rf "${OUT_DIR}"
mkdir -p "${OUT_DIR}" "${MBD_REPLAY_DIR}" "${FEM_REPLAY_DIR}"

if [[ -d "${MIXED_INPUT}" ]]; then
    INPUT_ONEWAY_DIR="$(cd "${MIXED_INPUT}" && pwd)"
    [[ -f "${INPUT_ONEWAY_DIR}/mixed_bundle/provenance_manifest.json" ]] || {
        echo "FAIL: mixed oneway outdir missing provenance manifest: ${INPUT_ONEWAY_DIR}" >&2
        exit 1
    }
    cp -R "${INPUT_ONEWAY_DIR}/." "${MIXED_ONEWAY_DIR}/"
else
    MIXED_MANIFEST="${MIXED_INPUT}"
    python3 "${ROOT_DIR}/scripts/validate_mixed_macro_local_generic_manifest.py" "${MIXED_MANIFEST}"
    bash "${ROOT_DIR}/tools/runners/mixed_bounded/run_mixed_macro_local_oneway_generic_v1.sh" "${MIXED_MANIFEST}" "${MIXED_ONEWAY_DIR}"
fi

python3 "${ROOT_DIR}/tools/exporters/mixed_bounded/export_mixed_local_feedback_reduced_generic.py" "${MIXED_ONEWAY_DIR}"

python3 - "${MBD_DECK}" "${REDUCED_DIR}/mbd_local_feedback_reduced.csv" "${MBD_REPLAY_DIR}/replay_from_mixed_feedback.dat" <<'PY'
