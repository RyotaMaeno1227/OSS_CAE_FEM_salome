for manifest_row in source_rows:
    if not isinstance(manifest_row, dict):
        fail("mixed feedback manifest row must be an object")
    engine = manifest_row.get("source_engine")
    feedback_row_key = manifest_row.get("feedback_row_key")
    feedback_csv = manifest_row.get("feedback_csv")
