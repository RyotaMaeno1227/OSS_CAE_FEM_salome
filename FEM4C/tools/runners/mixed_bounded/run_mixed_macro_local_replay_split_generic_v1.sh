        if feedback_row is None:
            fail(f"missing FEM reduced feedback row for load_step={load_step} pair_id={pair_id}")
        if abs(gamma_n_used - float(feedback_row["gamma_n"])) > 1.0e-12:
            fail(f"FEM replay gamma_n_used mismatch at load_step={load_step} pair_id={pair_id}")
        fem_external_rows += 1
        fem_applied_feedback_keys.add(expected_key)
    elif fallback_applied:
        fem_fallback_rows += 1
    if fallback_applied:
        if abs(gamma_n_used - 1.0) > 1.0e-12:
            fail(f"FEM fallback gamma_n_used must be 1.0 at load_step={load_step} pair_id={pair_id}")
        if abs(k_pen_used - k_pen_base) > 1.0e-9:
            fail(f"FEM fallback k_pen_used must equal k_pen_base at load_step={load_step} pair_id={pair_id}")
        if load_step > 0:
            later_step_fem_fallback_rows += 1
    if load_step > 0:
        if abs(gamma_n_used - 1.0) > 1.0e-12:
            later_step_fem_gamma_shift_rows += 1
        if abs(k_pen_used - k_pen_base) > 1.0e-9:
            later_step_fem_k_shift_rows += 1
    if manifest_row is not None:
        fem_links.append(
            {
                "source_row_count": int(manifest_row.get("source_row_count", 0)),
                "valid_source_row_count": int(manifest_row.get("valid_source_row_count", 0)),
                "invalid_source_row_count": int(manifest_row.get("invalid_source_row_count", 0)),
                "reduced_feedback_csv_path": str(mixed_oneway_dir / "reduced_feedback" / "fem_local_feedback_reduced.csv"),
                "reduced_feedback_row_key": {"load_step": expected_key[0], "pair_id": expected_key[1]},
                "replay_consume_artifact": str(fem_replay_dir / "replay_generic.out.fem_contact_generic_replay_use.csv"),
